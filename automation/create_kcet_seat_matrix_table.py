
import sys
from pathlib import Path

# Add the project root directory to Python's import path
PROJECT_ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(PROJECT_ROOT))

from app import get_db_connection


def create_seat_matrix_table():
    connection = get_db_connection()

    try:
        connection.execute("""
            CREATE TABLE IF NOT EXISTS kcet_seat_matrix_2026 (
                id BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
                source_year INTEGER NOT NULL,
                pdf_page INTEGER NOT NULL,
                college_code TEXT NOT NULL,
                college_name TEXT NOT NULL,
                course_code TEXT NOT NULL,
                course_name TEXT NOT NULL,
                seat_type TEXT NOT NULL
                    CHECK (seat_type IN ('HK', 'RK')),

                general_c1 INTEGER NOT NULL,
                general_2a INTEGER NOT NULL,
                general_2b INTEGER NOT NULL,
                general_3a INTEGER NOT NULL,
                general_3b INTEGER NOT NULL,
                general_st INTEGER NOT NULL,
                general_sca INTEGER NOT NULL,
                general_scb INTEGER NOT NULL,
                general_scc INTEGER NOT NULL,
                general_scc_20 INTEGER NOT NULL,
                general_gm INTEGER NOT NULL,

                kannada_c1 INTEGER NOT NULL,
                kannada_2a INTEGER NOT NULL,
                kannada_2b INTEGER NOT NULL,
                kannada_3a INTEGER NOT NULL,
                kannada_3b INTEGER NOT NULL,
                kannada_st INTEGER NOT NULL,
                kannada_sca INTEGER NOT NULL,
                kannada_scb INTEGER NOT NULL,
                kannada_scc INTEGER NOT NULL,
                kannada_scc_20 INTEGER NOT NULL,
                kannada_gm INTEGER NOT NULL,

                rural_c1 INTEGER NOT NULL,
                rural_2a INTEGER NOT NULL,
                rural_2b INTEGER NOT NULL,
                rural_3a INTEGER NOT NULL,
                rural_3b INTEGER NOT NULL,
                rural_st INTEGER NOT NULL,
                rural_sca INTEGER NOT NULL,
                rural_scb INTEGER NOT NULL,
                rural_scc INTEGER NOT NULL,
                rural_scc_20 INTEGER NOT NULL,
                rural_gm INTEGER NOT NULL,

                total_hk_rk INTEGER NOT NULL,

                UNIQUE (source_year, college_code, course_code, seat_type)
            )
        """)

        connection.commit()
        print("Table kcet_seat_matrix_2026 is ready.")

    except Exception:
        connection.rollback()
        raise

    finally:
        connection.close()


if __name__ == "__main__":
    create_seat_matrix_table()
